// The three rules that name the default panel: the one that shows when the
// address bar names no panel, and the two that hide it again once another panel
// is targeted. Generated because which panel opens the page is layout.mjs's
// decision, and duplicating that id in a stylesheet is how the two drift apart.
export const defaultPaneRules = ({ defaultPaneId }) =>
  [
    `#panes > #${defaultPaneId} { display: block; }`,
    `#panes > :target ~ #${defaultPaneId} { display: none; }`,
    `#panes > :has(:target) ~ #${defaultPaneId} { display: none; }`,
  ].join('\n')

// One rule per panel, generated so the nav can mark the current entry without
// JavaScript. Each panel gets two selectors: the panel itself being the target,
// and something inside it being the target (a deep link such as #api-images).
export const navCurrentRules = ({ paneIds, defaultPaneId }) => {
  const marker = `{background:var(--cluster);border-left-color:var(--accent);font-weight:600}`
  const perPane = paneIds
    .flatMap((id) => [
      `body:has(#${id}:target) [data-pane="${id}"]`,
      `body:has(#${id} :target) [data-pane="${id}"]`,
    ])
    .map((selector) => `${selector}${marker}`)
  const fallback = `body:not(:has(#panes :target)) [data-pane="${defaultPaneId}"]${marker}`
  return [...perPane, fallback].join('\n')
}
