// The stylesheet for the navigation shell, appended after tools/docs/styles.mjs.
// It is additive: the handful of rules that supersede the old single-column
// layout win on source order, and no rule here introduces a url(), an @import or
// an @font-face, because the page has to render identically with the network
// unplugged.
//
// How one-panel-at-a-time works, and why it is built this way:
//   * `.pane`/`.phase` children of #panes are hidden; `:target` shows the one the
//     address bar names. That is the whole mechanism, and it needs no JavaScript.
//   * With no fragment at all, the default panel shows — which panel that is
//     belongs to layout.mjs, so those three rules are generated by
//     `defaultPaneRules` below rather than written here. The default panel is the
//     LAST child of #panes so that `#panes > :target ~ #<default>` can hide it
//     once a panel is chosen — a general sibling combinator, supported
//     everywhere, rather than `:has()`.
//     DOM order is invisible to the reader because exactly one panel is ever
//     displayed.
//   * `:has()` appears only in progressive enhancements (deep links into a panel,
//     the current-panel marker in the nav). Where it is missing, the page still
//     switches panels correctly; it just does not highlight, and the script sets
//     aria-current anyway.
